"""Generate the guest's import trampolines and the host's import table from port/imports.list.

Guest side (imports.s, ELF assembly): each import is a 3-instruction trampoline that jumps
through a 64-bit slot of __host_import_table, which the host loader fills in. Arguments stay
in their registers, so the host function receives exactly what the guest passed.

Host side (host_imports.c): a name -> function table for host_resolve_import().

Usage: gen_imports.py guest_imports.s host_imports.c imports.list [more.list ...]
"""

import sys


def read_list(path):
    entries = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                parts = line.split()
                entries.append((parts[0], parts[1] if len(parts) > 1 else parts[0]))
    return entries


def guest_asm(entries):
    out = ["\t.text"]
    for i, (guest, _) in enumerate(entries):
        out += [
            f"\t.globl {guest}",
            f"\t.type {guest},%function",
            "\t.p2align 2",
            f"{guest}:",
            f"\tadrp x16, __host_import_table+{8 * i}",
            f"\tldr x16, [x16, :lo12:__host_import_table+{8 * i}]",
            "\tbr x16",
        ]
    out += ['\t.section .rodata,"a",@progbits', "\t.globl __host_import_names", "__host_import_names:"]
    out += [f'\t.asciz "{host}"' for _, host in entries]
    out += ["\t.globl __host_import_count", "\t.p2align 2", "__host_import_count:",
            f"\t.long {len(entries)}"]
    out += ["\t.data", "\t.globl __host_import_table", "\t.p2align 3", "__host_import_table:",
            f"\t.zero {8 * max(len(entries), 1)}"]
    return "\n".join(out) + "\n"


def host_c(entries):
    hosts = sorted({host for _, host in entries})
    out = ["/* Generated by port/tools/gen_imports.py from port/imports.list. */",
           "#include <string.h>", ""]
    out += [f"extern void {h}(void);" for h in hosts]
    out += ["", "static const struct { const char *name; void (*function)(void); } imports[] = {"]
    out += [f'    {{"{h}", {h}}},' for h in hosts]
    out += ["};", "",
            "void (*host_resolve_import(const char *name))(void)",
            "{",
            "    for (unsigned i = 0; i < sizeof imports / sizeof imports[0]; i++)",
            "        if (!strcmp(imports[i].name, name)) return imports[i].function;",
            "    return 0;",
            "}"]
    return "\n".join(out) + "\n"


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    entries = [e for path in sys.argv[3:] for e in read_list(path)]
    write(sys.argv[1], guest_asm(entries))
    write(sys.argv[2], host_c(entries))


if __name__ == "__main__":
    main()
