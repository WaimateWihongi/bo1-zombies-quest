"""OpenGL ES bindings for the guest, generated from the NDK's own GLES3/gl32.h.

The guest is ILP32, the host's libGLESv3 is LP64. Plain GL arguments (enums, ints, floats,
GLint64) mean the same in both, but pointers and GLsizeiptr/GLintptr are 32 bits wide in the
guest. For each function named in port/gl.list this writes a host wrapper that takes those
arguments as 32-bit values and widens them, plus the import-list lines that route the guest's
glXxx to the wrapper.

Functions marked `special` in gl.list have hand-written host wrappers in port/host/host_gl.c
(they pass pointers to pointers, or return pointers the guest must be able to read).

usage: gen_gl.py <gl32.h> <gl.list> <out imports.list> <out host wrappers .c> <out guest table .c>
"""
import re
import sys

WIDE_INTS = {"GLsizeiptr", "GLintptr"}


def parse_header(path):
    text = open(path, encoding="utf-8").read()
    protos = {}
    for m in re.finditer(r"GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(gl\w+)\s*\(([^)]*)\)\s*;", text):
        protos[m[2]] = (m[1].strip(), m[3].strip())
    return protos


def read_list(path):
    entries = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].split()
        if line:
            entries.append((line[0], "special" in line[1:]))
    return entries


def split_params(params):
    if params in ("", "void"):
        return []
    out = []
    for p in params.split(","):
        p = p.strip()
        m = re.match(r"(.*?)(\w+)$", p)
        out.append((m[1].strip(), m[2]))
    return out


FLOATS = {"GLfloat", "GLclampf"}
WIDE_64 = {"GLint64", "GLuint64"}


def wrapper(name, ret, params):
    """The host wrapper. Arguments past the eight integer (or eight float) registers sit on the
    stack, and the two ABIs lay that out differently: the guest's (arm64_32, Apple's rules)
    packs each argument at its own size, 4 bytes for an int or a guest pointer, while the host's
    (AAPCS64) gives every argument an 8-byte slot. So the wrapper takes the guest's stack area
    as raw 64-bit words and picks each argument out at the guest's offset; taking them as plain
    parameters would read every one after the first from the wrong place."""
    if "*" in ret or ret == "GLsync":
        sys.exit(f"gen_gl: {name} returns a pointer; mark it special and write its wrapper by hand")
    reg_params, stack_args, call_args = [], [], []
    ints = floats = stack = 0
    for i, (ptype, pname) in enumerate(params):
        if "*" in ptype or ptype in ("GLsync", "GLDEBUGPROC", "GLDEBUGPROCKHR"):
            if "**" in ptype.replace(" ", "") or "*const*" in ptype.replace(" ", ""):
                sys.exit(f"gen_gl: {name} takes a pointer to pointers; mark it special")
            host_type, cast = "uint32_t", f"({ptype})(uintptr_t)"
        elif ptype in WIDE_INTS:
            host_type, cast = "int32_t", f"({ptype})"
        else:
            host_type, cast = ptype, ""
        is_float = ptype in FLOATS
        size = 8 if ptype in WIDE_64 else 4
        if is_float and floats < 8:
            floats += 1
            reg_params.append(f"{host_type} a{i}")
        elif not is_float and ints < 8:
            ints += 1
            reg_params.append(f"{host_type} a{i}")
        else:
            stack = (stack + size - 1) // size * size
            stack_args.append((i, host_type, size, stack))
            stack += size
        call_args.append(f"{cast}a{i}")
    words = (stack + 7) // 8
    if stack_args and ints < 8:
        sys.exit(f"gen_gl: {name} spills floats with integer registers free; write its wrapper by hand")
    sig = ", ".join(reg_params + [f"uint64_t s{w}" for w in range(words)]) or "void"
    unpack = ""
    if stack_args:
        unpack = f"    const uint64_t stack[{words}] = {{{', '.join(f's{w}' for w in range(words))}}};\n"
        for i, host_type, size, offset in stack_args:
            unpack += f"    {host_type} a{i};\n    memcpy(&a{i}, (const char *)stack + {offset}, {size});\n"
    body = f"{name}({', '.join(call_args)})"
    if ret == "void":
        return f"void hgl_{name}({sig})\n{{\n{unpack}    {body};\n}}\n"
    return f"{ret} hgl_{name}({sig})\n{{\n{unpack}    return {body};\n}}\n"


def main():
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    header, listing, out_list, out_host, out_guest = sys.argv[1:]
    protos = parse_header(header)
    entries = read_list(listing)
    imports, host = [], ["/* Generated by port/tools/gen_gl.py: the guest's GL calls, widened for the host. */",
                         "#include <stdint.h>", "#include <string.h>", "#include <GLES3/gl32.h>", ""]
    guest = ["/* Generated by port/tools/gen_gl.py: name -> function, for MOJOSHADER_glCreateContext. */",
             "#include <stddef.h>", "#include <string.h>", "#include <GLES3/gl32.h>", ""]
    for name, special in entries:
        if name not in protos:
            sys.exit(f"gen_gl: {name} is not in {header}")
        imports.append(f"{name} hgl_{name}")
        if not special:
            ret, params = protos[name]
            host.append(wrapper(name, ret, split_params(params)))
    guest.append("static const struct { const char *name; void *function; } gl_functions[] = {")
    guest += [f'    {{"{name}", (void *){name}}},' for name, _ in entries]
    guest += ["};", "",
              "void *bo1_gl_lookup(const char *name)",
              "{",
              "    for (size_t i = 0; i < sizeof gl_functions / sizeof gl_functions[0]; i++)",
              "        if (!strcmp(gl_functions[i].name, name)) return gl_functions[i].function;",
              "    return NULL;",
              "}", ""]
    for path, lines in ((out_list, imports), (out_host, host), (out_guest, guest)):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
